"""Сведение подписей страницы лота к одному написанию.

Площадки движка называют одно и то же поле по-разному: «Обеспечение задатка»
у tendergarant и utender — это «Обеспечение заявки» остальных, etpu_bankrupt
дописывает к датам «(Московское время)», у части площадок «pуб.» с латинской
«p». Пока это разные ключи, один запрос по полю приходится писать под каждую
площадку, а новое поле не отличить от старого в другом написании.

Правила выведены по выгрузке в соседнем проекте разведки данных
(``analytica/explore/build_label_registry.py``, таблица ``label_synonyms.json``)
и перенесены сюда кодом: JSON там — источник, в рантайме он не читается.
Синоним заносится, только если это то же поле; сомнительное не сводится.

«Причина отказа победителя (Иванов И. И.)» — не подпись, а данные: имя
участника живёт в названии поля, и каждый такой ключ одноразовый. Такие пары
выносятся из раздела в список отказов.
"""

from __future__ import annotations

import re
from typing import Any

#: Разделы-синонимы -> каноническое имя раздела.
SECTIONS = {
    "Обеспечение задатка": "Обеспечение заявки",
    "Заключение договора купли-продажи": "Информация о договоре купли-продажи",
}

#: Подписи-синонимы -> каноническая подпись. Применяется после сведения
#: раздела и среза уточнений, поэтому ключи — уже без «(Московское время)».
LABELS = {
    # «Обеспечение задатка» (tendergarant, utender) -> «Обеспечение заявки»
    "Дата внесения задатка": "Дата внесения обеспечения",
    "Дата возврата задатка": "Дата возврата обеспечения",
    "Порядок внесения и возврата задатка": "Порядок внесения и возврата обеспечения",
    "Размер задатка, руб.": "Размер обеспечения, руб.",
    # «Заключение договора» (utender) -> «Информация о договоре»
    "С кем заключен договор": "Договор заключен с",
    # латинская «p» в «pуб.»
    "Цена договора, pуб.": "Цена договора, руб.",
    # utender: «участниками торгов» вместо «заявителями»
    "Порядок оформления участия в торгах, перечень представляемых участниками торгов документов "
    "и требования к их оформлению": "Порядок оформления участия в торгах, перечень представляемых "
    "заявителями документов и требования к их оформлению",
    # три написания одной даты публикации
    "Дата публикации в печатном органе по месту нахождения": "Дата публикации в печатном органе "
    "по месту нахождения должника",
    "Дата публикации в печатном органе по месту нахождения должника или иных СМИ": "Дата публикации "
    "в печатном органе по месту нахождения должника",
}

#: Уточнение, которое etpu_bankrupt дописывает в конец подписи.
SUFFIX_RE = re.compile(r"\s*\(\s*Московское время\s*\)\s*$")

#: «Причина отказа победителя (ФИО)», «…участника, занявшего 2 место (ФИО)».
#: Шаблон из разведки (``\S+`` на роль) второй вариант не ловил: между ролью
#: и скобкой стоит «, занявшего N место».
REFUSAL_RE = re.compile(
    r"^Причина отказа (?P<role>победителя|участника)(?:, занявшего (?P<place>\d+) место)?\s*\((?P<party>.+)\)$"
)


def canon_section(section: str) -> str:
    return SECTIONS.get(section, section)


def canon_label(label: str) -> str:
    label = SUFFIX_RE.sub("", label).strip()
    return LABELS.get(label, label)


def parse_refusal(label: str, reason: Any) -> dict[str, Any] | None:
    """Отказ из подписи «Причина отказа …»; ``None`` — это обычная подпись."""
    match = REFUSAL_RE.match(label)
    if match is None:
        return None
    refusal: dict[str, Any] = {"role": match["role"], "party": match["party"], "reason": reason}
    if match["place"]:
        refusal["place"] = int(match["place"])
    return refusal


def canon_detail(
    sections: dict[str, dict[str, Any]],
) -> tuple[dict[str, dict[str, Any]], list[dict[str, Any]]]:
    """Разделы страницы как на площадке -> (сведённые разделы, отказы).

    Работает на словаре, а не на странице, чтобы тем же правилом можно было
    свести и уже сохранённый ``extra``, не обходя площадки заново.

    Если два написания одного поля встретились на одной странице, остаётся
    первое непустое: терять значение ради порядка ключей незачем.
    """
    canon: dict[str, dict[str, Any]] = {}
    refusals: list[dict[str, Any]] = []
    for section, pairs in sections.items():
        target = canon.setdefault(canon_section(section), {})
        for label, value in pairs.items():
            label = canon_label(label)
            if (refusal := parse_refusal(label, value)) is not None:
                refusals.append(refusal)
            elif target.get(label) is None:
                target[label] = value
    # Раздел, в котором были одни отказы, пустым не оставляем.
    return {section: pairs for section, pairs in canon.items() if pairs}, refusals
