def unknown_labels(extra: dict[str, dict[str, Any]]) -> list[str]:
    """Пары «раздел :: подпись», которых нет в реестре; незнакомый раздел — целиком."""
    unknown: list[str] = []
    for section, pairs in extra.items():
        known = KNOWN_LABELS.get(section)
        if known is None:
            unknown.append(f"{section} :: *")
            continue
        unknown.extend(f"{section} :: {label}" for label in pairs if label not in known)
    return unknown
